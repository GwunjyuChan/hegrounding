const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const assert=require('node:assert/strict');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'he-review-test-'));
const python=path.resolve(__dirname,'../../..','.venv/bin/python');
let server,browser;

(async()=>{
  for(const name of ['annotations.jsonl','manifest.json','review.html'])fs.copyFileSync(path.join(__dirname,name),path.join(root,name));
  server=spawn(python,[path.join(__dirname,'serve_reviews.py'),'--port','0','--root',root],{stdio:['ignore','pipe','pipe']});
  const url=await new Promise((resolve,reject)=>{
    let output='';server.stdout.on('data',chunk=>{output+=chunk;const match=output.match(/http:\/\/127\.0\.0\.1:\d+\/review.html/);if(match)resolve(match[0]);});
    server.on('error',reject);server.on('exit',code=>reject(Error(`Server exited ${code}`)));
  });
  browser=await chromium.launch({headless:true,executablePath:'/opt/pw-browsers/chromium',args:['--no-proxy-server']});
  const context=await browser.newContext({viewport:{width:1440,height:960}});
  // The checks below read the English half of the messages; the language switch has its own check at the end.
  await context.addInitScript(()=>localStorage.setItem('he-language','en'));
  const page=await context.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(String(error)));
  await page.goto(url+'#MF0013');
  await page.waitForFunction(()=>!document.querySelector('[data-decision="accepted"]').disabled);
  assert.equal(fs.existsSync(path.join(root,'human_reviews.jsonl')),false);
  await page.fill('#reviewer','UI test reviewer');
  await page.click('[data-decision="accepted"]');
  await page.fill('#review-notes','Checked the suburb, not the nearby convent.');
  await page.click('#review-save');
  await page.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Saved to disk'));
  let rows=fs.readFileSync(path.join(root,'human_reviews.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(rows.length,1);assert.equal(rows[0].decision,'accepted');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('[data-decision="accepted"]').getAttribute('aria-pressed')==='true');
  assert.equal(await page.inputValue('#review-notes'),'Checked the suburb, not the nearby convent.');
  await page.screenshot({path:'/private/tmp/human-review-desktop.png',fullPage:true});
  await page.click('[data-decision="needs_changes"]');
  await page.fill('#review-notes','Shorten the eastern edge.');
  await page.selectOption('#event-select','MF0014');
  await page.selectOption('#event-select','MF0013');
  assert.equal(await page.inputValue('#review-notes'),'Shorten the eastern edge.');
  await page.click('#review-save-next');
  await page.waitForFunction(()=>document.getElementById('event-title').textContent==='MF0014');
  await page.selectOption('#review-filter','needs_changes');
  assert.equal(await page.locator('#event-select option').count(),1);
  assert.equal(await page.locator('#event-title').innerText(),'MF0013');
  await page.selectOption('#review-filter','all');
  await page.selectOption('#event-select','MF0013');
  const other=await context.newPage();await other.goto(url+'#MF0013');
  await other.waitForFunction(()=>!document.querySelector('[data-decision="accepted"]').disabled);
  await page.click('[data-decision="needs_evidence"]');
  await page.fill('#review-notes','Need a second source.');await page.click('#review-save');
  await page.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Saved to disk'));
  await other.click('[data-decision="rejected"]');await other.fill('#review-notes','Stale tab must not overwrite.');await other.click('#review-save');
  await other.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Another tab'));
  rows=fs.readFileSync(path.join(root,'human_reviews.jsonl'),'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(rows.length,3);assert.equal(rows.at(-1).decision,'needs_evidence');
  other.on('dialog',d=>d.accept());await other.click('#review-reload');
  await other.waitForFunction(()=>document.querySelector('[data-decision="needs_evidence"]').getAttribute('aria-pressed')==='true');
  await other.close();
  await page.selectOption('#event-select','Z0003');
  assert(await page.locator('[data-decision="accepted"]').isDisabled());
  await page.selectOption('#event-select','MF0013');
  await page.click('[data-decision="rejected"]');await page.fill('#review-notes','');await page.click('#review-save');
  assert((await page.locator('#review-message').innerText()).includes('Add a reason'));
  page.on('dialog',d=>d.accept());await page.click('#review-reload');
  await page.waitForFunction(()=>document.querySelector('[data-decision="needs_evidence"]').getAttribute('aria-pressed')==='true');
  let tokenRetry=false;
  await page.route('**/api/reviews',route=>{
    if(route.request().method()==='POST' && !tokenRetry){tokenRetry=true;return route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({error:'Rotated token'})});}
    return route.continue();
  });
  await page.click('[data-decision="needs_changes"]');await page.fill('#review-notes','Token renewal must preserve this draft.');await page.click('#review-save');
  await page.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Saved to disk'));
  assert(tokenRetry);await page.unroute('**/api/reviews');
  await page.route('**/api/reviews',route=>route.request().method()==='POST' ? route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Test disk failure'})}) : route.continue());
  await page.click('[data-decision="needs_evidence"]');await page.fill('#review-notes','Keep me if saving fails.');await page.click('#review-save');
  await page.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Test disk failure'));
  assert.equal(await page.inputValue('#review-notes'),'Keep me if saving fails.');
  await page.unroute('**/api/reviews');await page.click('#review-save');
  await page.waitForFunction(()=>document.getElementById('review-message').textContent.includes('Saved to disk'));
  await page.setViewportSize({width:390,height:844});
  await page.locator('.human-review').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/private/tmp/human-review-mobile.png',fullPage:true});
  const buttonBoxes=await page.locator('.review-options button').evaluateAll(nodes=>nodes.map(n=>({width:n.clientWidth,scroll:n.scrollWidth})));
  assert(buttonBoxes.every(b=>b.scroll<=b.width));
  // Language: Chinese by default, English after the switch, kept across reloads, and no Chinese left in the controls.
  const langContext=await browser.newContext({viewport:{width:1440,height:960}});
  const lang=await langContext.newPage();lang.on('pageerror',error=>errors.push(String(error)));
  await lang.goto(url+'#MF0013');
  await lang.waitForFunction(()=>!document.querySelector('[data-decision="accepted"]').disabled);
  assert.equal(await lang.locator('#review-save-next').innerText(),'保存并下一题');
  assert.equal(await lang.locator('html').getAttribute('lang'),'zh-CN');
  await lang.selectOption('#language-select','en');
  assert.equal(await lang.locator('#review-save-next').innerText(),'Save and next');
  assert.equal(await lang.locator('html').getAttribute('lang'),'en');
  const han=/[\u3400-\u9fff]/;
  const chrome=await lang.evaluate(()=>[...document.querySelectorAll('header, .filters option, .tool-row, .review-options, .review-actions, #review-message, .section-label, #more-info > summary, #more-info h3, #event-status, .candidate .k')].map(n=>n.innerText||n.textContent).join('\n')+[...document.querySelectorAll('[title]:not(#language-select),[placeholder]')].map(n=>(n.title||'')+(n.placeholder||'')).join('\n'));
  assert(!han.test(chrome.replace(/中文/g,'')),'Chinese left in English controls: '+chrome.replace(/中文/g,'').match(/.{0,30}[\u3400-\u9fff].{0,30}/)?.[0]);
  assert.equal(await lang.title(),'HE Grounding | Review');
  // The AI notes switch too (display-only English from display_en.json).
  const noteIds=['location','caveat','map-evidence','text-evidence','screening-issue','source-note'];
  const notes=await lang.evaluate(ids=>ids.map(id=>document.getElementById(id).textContent).join('\n'),noteIds);
  assert(!han.test(notes),'Chinese left in English notes: '+notes.match(/.{0,30}[\u3400-\u9fff].{0,30}/)?.[0]);
  assert((await lang.locator('#caveat').innerText()).trim());
  await lang.reload();
  await lang.waitForFunction(()=>!document.querySelector('[data-decision="accepted"]').disabled);
  assert.equal(await lang.locator('#language-select').inputValue(),'en');
  assert.equal(await lang.locator('#review-save-next').innerText(),'Save and next');
  await lang.selectOption('#language-select','zh');
  assert.equal(await lang.locator('#review-save-next').innerText(),'保存并下一题');
  assert(han.test(await lang.locator('#caveat').innerText()));
  assert((await lang.locator('#event-select option').first().innerText()).includes('·'));
  await langContext.close();
  assert.deepEqual(errors,[]);
  assert.equal(fs.readFileSync(path.join(root,'annotations.jsonl'),'utf8'),fs.readFileSync(path.join(__dirname,'annotations.jsonl'),'utf8'));
  console.log(JSON.stringify({save_reload:'passed',revise_and_history:'passed',unsaved_navigation:'passed',review_filter:'passed',stale_tab_protection:'passed',null_geometry_guard:'passed',required_notes:'passed',csrf_token_retry:'passed',failed_save_preserves_notes:'passed',mobile_no_overflow:true,language_switch:'passed',page_errors:errors,test_data:'temporary directory only'},null,2));
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{
  if(browser)await browser.close();
  if(server?.pid){const exited=new Promise(resolve=>server.once('exit',resolve));if(server.exitCode===null){server.kill('SIGTERM');await exited;}}
  fs.rmSync(root,{recursive:true,force:true});
});
